import React from "react";
import { FlatList, Pressable, StyleSheet, Text, View } from "react-native";
import { SafeAreaView } from "react-native-safe-area-context";
import { useRouter } from "expo-router";
import { FontAwesome } from "@expo/vector-icons";
import { COLORS } from "../../theme/theme";
import { useWorkouts } from "../../WorkoutContext";
import { confirmAction, formatNumber } from "../../confirm";
import { WEIGHT_UNIT } from "../../types";

const Home = () => {
  const router = useRouter();
  const { workouts, deleteWorkout, records } = useWorkouts();
  // typed-route definitions are regenerated by the dev server, so accept any path here
  const go = (path: string) => router.push(path as never);

  return (
    <SafeAreaView style={styles.container} edges={["top"]}>
      <View style={styles.headerRow}>
        <Text style={styles.title}>WORKOUTS</Text>
        <Pressable
          onPress={() => go("/workout/create")}
          style={styles.newBtn}
        >
          <FontAwesome name="plus" size={14} color={COLORS.primaryWhiteHex} />
          <Text style={styles.newBtnText}>  New</Text>
        </Pressable>
      </View>

      <FlatList
        data={workouts}
        keyExtractor={(item) => item.id}
        contentContainerStyle={styles.list}
        renderItem={({ item }) => (
          <View style={styles.workoutItem}>
            <View style={styles.itemHeader}>
              <View style={{ flex: 1 }}>
                <Text style={styles.workoutText}>{item.name}</Text>
                <Text style={styles.workoutSub}>
                  {item.exercises.length} exercise
                  {item.exercises.length === 1 ? "" : "s"}
                </Text>
              </View>
              <Pressable
                hitSlop={10}
                onPress={() =>
                  confirmAction(
                    "Delete workout?",
                    `"${item.name}" will be permanently removed.`,
                    "Delete",
                    () => deleteWorkout(item.id)
                  )
                }
              >
                <FontAwesome name="trash" size={20} color={COLORS.primaryRedHex} />
              </Pressable>
            </View>

            {item.exercises.map((ex, i) => {
              const best = records[ex.exerciseId]?.best;
              return (
                <View key={`${ex.exerciseId}-${i}`} style={styles.exRow}>
                  <Text style={styles.exName} numberOfLines={1}>
                    {ex.name}
                  </Text>
                  <Text style={styles.exSets}>
                    {ex.sets} x {ex.reps}
                  </Text>
                  {best && (
                    <Text style={styles.exBest}>
                      {formatNumber(best.weight)} {WEIGHT_UNIT} x {best.reps}
                    </Text>
                  )}
                </View>
              );
            })}

            <Pressable
              style={styles.startBtn}
              onPress={() => go(`/workout/${item.id}`)}
            >
              <FontAwesome name="play" size={14} color={COLORS.primaryWhiteHex} />
              <Text style={styles.startBtnText}>  Start Workout</Text>
            </Pressable>
          </View>
        )}
        ListEmptyComponent={
          <View style={styles.emptyContainer}>
            <Text style={styles.emptyText}>No Workouts</Text>
            <Pressable
              onPress={() => go("/workout/create")}
              style={styles.createWorkoutBtn}
            >
              <Text style={styles.createWorkoutBtnText}>Create a Workout</Text>
            </Pressable>
          </View>
        }
      />
    </SafeAreaView>
  );
};

const styles = StyleSheet.create({
  container: { flex: 1, backgroundColor: COLORS.primaryGreyHex },
  headerRow: {
    flexDirection: "row",
    alignItems: "center",
    justifyContent: "space-between",
    paddingHorizontal: 16,
    paddingVertical: 12,
  },
  title: { color: COLORS.primaryRedHex, fontSize: 30 },
  newBtn: {
    flexDirection: "row",
    alignItems: "center",
    backgroundColor: COLORS.primaryRedHex,
    paddingVertical: 8,
    paddingHorizontal: 14,
    borderRadius: 8,
  },
  newBtnText: { color: COLORS.primaryWhiteHex, fontSize: 16 },
  list: { paddingHorizontal: 16, paddingBottom: 110 },
  emptyContainer: { marginTop: 40, alignItems: "center" },
  emptyText: { color: COLORS.primaryWhiteHex, fontSize: 20, marginBottom: 15 },
  createWorkoutBtn: {
    borderWidth: 2,
    borderColor: COLORS.primaryLightGreyHex,
    padding: 8,
    marginTop: 20,
  },
  createWorkoutBtnText: { fontSize: 20, color: COLORS.primaryWhiteHex },
  workoutItem: {
    padding: 14,
    marginVertical: 6,
    backgroundColor: COLORS.secondaryDarkGreyHex,
    borderRadius: 10,
  },
  itemHeader: { flexDirection: "row", alignItems: "center", marginBottom: 8 },
  workoutText: { color: COLORS.primaryWhiteHex, fontSize: 20 },
  workoutSub: { color: COLORS.secondaryLightGreyHex, fontSize: 12, marginTop: 2 },
  exRow: { flexDirection: "row", alignItems: "center", paddingVertical: 3 },
  exName: { color: COLORS.primaryWhiteHex, flex: 1, fontSize: 14 },
  exSets: { color: COLORS.secondaryLightGreyHex, fontSize: 13, marginLeft: 8 },
  exBest: { color: COLORS.primaryOrangeHex, fontSize: 12, marginLeft: 8 },
  startBtn: {
    flexDirection: "row",
    alignItems: "center",
    justifyContent: "center",
    marginTop: 12,
    padding: 10,
    borderRadius: 8,
    backgroundColor: COLORS.primaryRedHex,
  },
  startBtnText: { color: COLORS.primaryWhiteHex, fontSize: 16 },
});

export default Home;
